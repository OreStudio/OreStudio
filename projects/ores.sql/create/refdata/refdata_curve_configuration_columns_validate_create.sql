/**
 * Curve Configuration Value Guard
 *
 * Refuses a value outside the set of the ORE leaf the column holds. One
 * enforcement point, in the database, because every writer passes through it: the
 * screen, a publish job and a shell script get the same answer from the same set.
 *
 * The map names each column's leaf; the leaf's path resolves to the parameter and
 * so to the value set, exactly as the convention term guard resolves a term. A
 * column the map does not name is free text and passes. Generated by
 * projects/ores.sql/utility/generate_curve_column_guards.py. Do not edit by hand.
 */

create or replace function ores_refdata_validate_curve_values_fn()
returns trigger
security definer
set search_path = public, pg_temp
as $$
declare
    v_row jsonb := to_jsonb(NEW);
    v_column record;
    v_value text;
begin
    for v_column in
        select k.column_name, l.value_set_code
          from ores_refdata_curve_configuration_columns_tbl k
          join ores_reporting_ore_parameters_tbl p
            on p.schema_name = k.schema_name
           and p.xpath = k.xpath
           and p.tenant_id = ores_utility_system_tenant_id_fn()
           and p.valid_to = ores_utility_infinity_timestamp_fn()
          join ores_reporting_ore_parameter_setting_value_sets_tbl l
            on l.code = p.scope || ':' || p.name
           and l.valid_to = ores_utility_infinity_timestamp_fn()
         where k.entity_name = TG_ARGV[0]
           and k.tenant_id = ores_utility_system_tenant_id_fn()
           and k.valid_to = ores_utility_infinity_timestamp_fn()
    loop
        v_value := v_row ->> v_column.column_name;
        if v_value is null or v_value = '' then
            continue;
        end if;
        if not ores_reporting_value_in_set_fn(v_column.value_set_code, v_value) then
            raise exception 'Invalid value % for %.%: the value is not in set %.',
                v_value, TG_ARGV[0], v_column.column_name, v_column.value_set_code;
        end if;
    end loop;
    return NEW;
end;
$$ language plpgsql;


def staff():
    """The sample's Employees rows, shaped as the account artefacts need them."""
    employees = read_source("employees")
    by_id = {e["employee_id"]: e for e in employees}
    out = []
    for e in employees:
        first = e["first_name"].strip()
        last = e["last_name"].strip()
        username = f"{first}.{last}".lower()
        lines = e["address"].split("\n")
        reports_to = None
        if e["reports_to"]:
            manager = by_id[e["reports_to"]]
            reports_to = f"{manager['first_name']}.{manager['last_name']}".lower()
        out.append(dict(
            id=uuid5(f"account:{username}"),
            employee_id=e["employee_id"],
            username=username,
            full_name=f"{first} {last}",
            email=f"{username}@{EMAIL_DOMAIN}",
            account_type="user",
            role=STAFF_ROLES[e["employee_id"]],
            job_title=e["title"],
            reports_to_username=reports_to,
            business_unit_code=STAFF_UNITS[e["employee_id"]],
            street_line_1=lines[0],
            street_line_2=lines[1] if len(lines) > 1 else None,
            city=e["city"],
            state=e["region"] or None,
            country_code=COUNTRY_ALPHA2[e["country"]],
            postal_code=e["postal_code"],
            phone=e["homephone"],
            photo_key=staff_photo_key(e["employee_id"]),
        ))
    return out


def party_countries():
    """Every country the sample's customers and suppliers trade from."""
    seen = set()
    for name in ("customers", "suppliers"):
        for row in read_source(name):
            seen.add(COUNTRY_ALPHA2[row["country"]])
    return sorted(seen)


def party_counterparties():
    """The GLEIF counterparties the party may trade with, by LEI."""
    rows = load_acme("party_counterparties")
    gleif = [r["counterparty_lei"] for r in rows
             if r["company_code"] == TEMPLATE_COMPANY
             and not r["counterparty_lei"].startswith("9695")]
    return sorted(set(gleif))[:COUNTERPARTY_LINK_COUNT]



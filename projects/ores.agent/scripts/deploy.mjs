import { readFile, mkdir, copyFile, writeFile, lstat } from 'node:fs/promises';
import { resolve, join, sep } from 'node:path';
import { createHash } from 'node:crypto';
const [command, artifactArg, rootArg] = process.argv.slice(2);
if (command !== 'install' || !artifactArg || !rootArg) throw new Error('Usage: node scripts/deploy.mjs install <artifact-directory> <deployment-root>');
const artifact = resolve(artifactArg), root = resolve(rootArg);
if (root === artifact || root.startsWith(artifact + sep)) throw new Error('Deployment must be outside the artifact directory.');
const manifest = JSON.parse(await readFile(join(artifact, 'manifest.json'), 'utf8'));
if (manifest.component !== 'ores.agent' || !/^[a-zA-Z0-9.-]+$/.test(manifest.version)) throw new Error('Invalid artifact manifest.');
const entries = Object.entries(manifest.files);
if (entries.length !== 1 || entries[0][0] !== 'agent.mjs') throw new Error('Unexpected artifact files.');
const content = await readFile(join(artifact, 'agent.mjs'));
if ((await lstat(join(artifact, 'agent.mjs'))).isSymbolicLink()) throw new Error('Symlink artifacts are not supported.');
const hash = createHash('sha256').update(content).digest('hex');
if (hash !== manifest.files['agent.mjs']) throw new Error('Artifact checksum mismatch.');
const release = join(root, 'releases', `${manifest.version}-${hash.slice(0, 12)}`);
await mkdir(release, { recursive: true });
await mkdir(join(root, 'config'), { recursive: true });
await mkdir(join(root, 'logs'), { recursive: true });
await copyFile(join(artifact, 'agent.mjs'), join(release, 'agent.mjs'));
await writeFile(join(release, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify({ installed: release, started: false }));

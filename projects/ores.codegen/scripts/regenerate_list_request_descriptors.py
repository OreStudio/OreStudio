#!/usr/bin/env python3
"""Write the TypeScript table that describes every list request.

The services decode a list request strictly: a member the struct declares must
be present, `as_of` included even though it is optional. A caller in TypeScript
cannot read a C++ header, so it cannot know which members a list declares, and a
payload written by hand states them by guesswork -- or does not state them, and
the screen shows a refusal.

This emits one table from the headers, which are the truth. `completeListRequest`
in the wire protocol uses it to fill a payload before it is sent, so a caller
states only what it means and the rest is completed from the protocol.

Run with --check to compare the committed table with the headers.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PROJECTS = ROOT / "projects"
TARGET = (
    PROJECTS
    / "ores.web"
    / "packages"
    / "wire-protocol"
    / "src"
    / "generated"
    / "list_requests.ts"
)

STRUCT = re.compile(r"struct\s+(\w+)\s*\{(.*?)\n\};", re.S)
# The subject may be stated on the line after the `=`, which the generator has to
# read too: a request missed here is a request whose payload goes out incomplete.
SUBJECT = re.compile(r'static constexpr std::string_view nats_subject\s*=\s*"([^"]+)";')


def members_of(body: str) -> tuple[str, ...]:
    names = []
    for line in body.splitlines():
        line = line.strip()
        if not line.endswith(";") or "(" in line:
            continue
        if line.startswith("using ") or line.startswith("static ") or line.startswith("struct "):
            continue
        declared = re.match(r"(?:std::[^=;]*?\s+)?(\w+)\s*(?:=[^;]*)?;$", line)
        if declared:
            names.append(declared.group(1))
    return tuple(names)


def shapes() -> dict[str, dict[str, object]]:
    """Each list request: its subject, whether it carries as_of, its filter and rows."""
    found: dict[str, dict[str, object]] = {}
    for header in sorted(PROJECTS.glob("*/api/include/*/messaging/*_protocol.hpp")):
        structs = {m.group(1): m.group(2) for m in STRUCT.finditer(header.read_text())}
        for name, body in structs.items():
            if not re.fullmatch(r"list_\w+_request", name):
                continue
            subject = SUBJECT.search(body)
            if subject is None:
                continue
            filter_type = None
            named = re.search(r"std::optional<(\w+)>\s+filter\s*;", body)
            if named:
                filter_type = named.group(1)
            reply = name.replace("_request", "_response")
            reply_body = structs.get(reply, "")
            rows = tuple(
                member
                for member in members_of(reply_body)
                if re.search(r"std::vector<[^>]*>\s+" + member + r"\s*;", reply_body)
            )
            found[subject.group(1)] = {
                "asOf": bool(re.search(r"std::optional<[^>]+>\s+as_of\s*;", body)),
                "filter": members_of(structs.get(filter_type or "", "")),
                "rows": rows,
            }
    return found


def render(table: dict[str, dict[str, object]]) -> str:
    lines = [
        "/**",
        " * The shape of every list request, generated from the C++ protocol.",
        " *",
        " * A service decodes a list request strictly, so a payload must state every",
        " * member the request declares, including `as_of` where it declares one.",
        " * `completeListRequest` reads this table and fills what a caller left out.",
        " *",
        " * Generated by projects/ores.codegen/scripts/regenerate_list_request_descriptors.py.",
        " * Do not edit by hand: run the script instead.",
        " */",
        "",
        "/** What a list request declares beyond its paging and order. */",
        "export interface ListRequestShape {",
        "    readonly asOf: boolean;",
        "    readonly filter: readonly string[];",
        "    readonly rows: readonly string[];",
        "}",
        "",
        "export const LIST_REQUESTS: Readonly<Record<string, ListRequestShape>> = {",
    ]
    for subject in sorted(table):
        shape = table[subject]
        lines.append(f"    '{subject}': {{")
        lines.append(f"        asOf: {'true' if shape['asOf'] else 'false'},")
        # One member per line: prettier keeps that as it is, so the generated
        # file needs no formatting pass and the check compares like for like.
        for name, values in (("filter", shape["filter"]), ("rows", shape["rows"])):
            if values:
                lines.append(f"        {name}: [")
                for value in values:
                    lines.append(f"            '{value}',")
                lines.append("        ],")
            else:
                lines.append(f"        {name}: [],")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def formatted(path: Path, content: str) -> str:
    """The content as the project's prettier writes it.

    The table is a TypeScript source file, so it is held to the same style as
    the rest of the package. Formatting here rather than by hand keeps the
    generator and the check in step with whatever prettier decides.
    """
    package = ROOT / "projects" / "ores.web"
    path.write_text(content)
    subprocess.run(
        ["npx", "--no-install", "prettier", "--write", str(path)],
        cwd=package,
        check=False,
        capture_output=True,
    )
    return path.read_text()


def main() -> int:
    content = render(shapes())
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.is_file() else ""
        # Formatted beside the real file, so prettier resolves the same
        # configuration it would for the committed one.
        scratch = TARGET.with_name(".list_requests.check.ts")
        try:
            expected = formatted(scratch, content)
        finally:
            scratch.unlink(missing_ok=True)
        if current != expected:
            print(f"{TARGET.relative_to(ROOT)} is stale. Run the generator without --check.")
            return 1
        print(f"{TARGET.relative_to(ROOT)} matches the protocol ({len(content) and len(shapes())} list requests)")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    formatted(TARGET, content)
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(shapes())} list requests)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

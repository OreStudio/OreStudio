def load(name):
    with open(os.path.join(SCRIPT_DIR, f"{name}.json")) as f:
        return json.load(f)


def sql_str(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def sql_bool(v):
    return "true" if v else "false"


def sql_opt_bool(v):
    return "null" if v is None else sql_bool(v)


def sql_num(v):
    return "null" if v is None else repr(float(v))


def write(filename, content):
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    path = os.path.join(OUTPUT_DIR, filename)
    with open(path, "w") as f:
        f.write(content)
    print(f"Wrote {path}")


def dataset_upsert(code, subject_area, name, description, artefact_type,
                   methodology="OreStudio Code Generation Methodology"):
    def q(v):
        return v.replace("'", "''")
    return f"""    PERFORM ores_dq_datasets_upsert_fn(ores_utility_system_tenant_id_fn(),
        '{q(code)}',
        'ACME Corporation',
        '{q(subject_area)}',
        'Reference Data',
        'NONE',
        'Primary',
        'Synthetic',
        'Raw',
        '{q(methodology)}',
        '{q(name)}',
        '{q(description)}',
        'ACMEBANK',
        'ACME Corporation generated data',
        current_date,
        'Internal Use Only',
        '{q(artefact_type)}'
    );
"""



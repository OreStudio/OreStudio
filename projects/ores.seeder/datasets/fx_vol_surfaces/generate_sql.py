"""
Writes the populate script of the FX volatility surface blueprints: the system
tenant's recipe for each pair the derived source quotes, staged in the DQ
artefact tables of the refdata.fx_vol_surface_blueprints dataset with the
methodology that explains them (methodology.txt, beside this script).

Usage:
    python3 generate_sql.py
"""
import os
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
OUTPUT = os.path.join(ROOT, "projects", "ores.sql", "populate", "refdata",
                      "refdata_fx_vol_surface_blueprints_artefact_populate.sql")

NAMESPACE = uuid.UUID("3f0c6a52-9d1e-4b7a-8e25-6c4f1d0b9a73")
NIL = "00000000-0000-0000-0000-000000000000"

DATASET_CODE = "refdata.fx_vol_surface_blueprints"
METHODOLOGY = "FX Volatility Surface Blueprint Methodology"
METHODOLOGY_DESCRIPTION = ("The recipe the system calibrates each FX volatility surface by: "
                           "the pairs, pillars, sources, smile model and output grid, and the "
                           "sources each choice is taken from")
METHODOLOGY_URL = ("https://github.com/OreStudio/OreStudio/tree/main/projects/ores.seeder/"
                   "datasets/fx_vol_surfaces")

# The pairs the derived source quotes, in market quoting order, with the short-dated
# delta type of each pair's FX option convention in refdata.conventions.
PAIRS = [
    ("EUR", "USD", "Spot"),
    ("GBP", "USD", "Spot"),
    ("USD", "JPY", "PaSpot"),
    ("USD", "CHF", "PaSpot"),
    ("AUD", "USD", "Spot"),
    ("USD", "CAD", "PaSpot"),
    ("NZD", "USD", "Spot"),
    ("EUR", "GBP", "Spot"),
    ("EUR", "JPY", "PaSpot"),
    ("EUR", "CHF", "PaSpot"),
]

EXPIRIES = ["1W", "1M", "2M", "3M", "6M", "9M", "1Y"]
LABELS = ["ATM", "25RR", "25BF", "10RR", "10BF"]

# The strikes of the output grid, as (side, delta), with None for ATM.
GRID_STRIKES = [("Put", 10), ("Put", 25), None, ("Call", 25), ("Call", 10)]


def fx_option_convention_id(base, quote):
    return f"{base}-{quote}-FXOPTION"


def output_strikes(delta_type):
    return ",".join("ATM" if s is None else f"DEL/{delta_type}/{s[0]}/{s[1]}"
                    for s in GRID_STRIKES)


def ore_deltas():
    """The grid's strikes as the deltas an ORE FXVolatility of smile type Delta reads,
    such as 25P; the delta type is the convention's."""
    return ",".join("ATM" if s is None else f"{s[1]}{s[0][0]}" for s in GRID_STRIKES)


def new_uuid(key):
    return str(uuid.uuid5(NAMESPACE, key))


def q(text):
    return "'" + text.replace("'", "''") + "'"


def rows():
    blueprints, pillars, sources = [], [], []
    for base, quote, delta_type in PAIRS:
        name = f"{base}{quote}_SSVI"
        blueprint_id = new_uuid(f"blueprint:{name}")
        blueprints.append((blueprint_id, name, base, quote, fx_option_convention_id(base, quote),
                           output_strikes(delta_type)))
        for expiry in EXPIRIES:
            for label in LABELS:
                pillar_id = new_uuid(f"pillar:{name}:{expiry}:{label}")
                pillars.append((pillar_id, blueprint_id, expiry, label))
                sources.append((new_uuid(f"source:{name}:{expiry}:{label}:derived"), pillar_id))
    return blueprints, pillars, sources


def values(lines):
    return ",\n".join(f"        ({line})" for line in lines) + ";"


def script():
    with open(os.path.join(HERE, "methodology.txt")) as handle:
        steps = handle.read().rstrip("\n")
    with open(os.path.join(ROOT, "projects", "ores.sql", "populate", "refdata",
                           "refdata_populate.sql")) as handle:
        licence = handle.read().split("*/", 1)[0] + "*/\n"

    blueprints, pillars, sources = rows()
    blueprint_lines = [
        f"v_dataset_id, v_tenant_id, {q(i)}, 0, {q(NIL)}, {q(NIL)}, {q(name)}, {q(base)}, "
        f"{q(quote)}, {q(convention)}, 'ssvi', 'linear_total_variance', "
        f"{q(','.join(EXPIRIES))}, {q(strikes)}"
        for i, name, base, quote, convention, strikes in blueprints]
    pillar_lines = [
        f"v_dataset_id, v_tenant_id, {q(i)}, 0, {q(NIL)}, {q(blueprint)}, {q(expiry)}, {q(label)}"
        for i, blueprint, expiry, label in pillars]
    source_lines = [
        f"v_dataset_id, v_tenant_id, {q(i)}, 0, {q(NIL)}, {q(pillar)}, {q(NIL)}, 'derived', 1.0"
        for i, pillar in sources]

    return licence + f"""
-- =============================================================================
-- AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
-- Generated by projects/ores.seeder/datasets/fx_vol_surfaces/generate_sql.py.
-- To change a blueprint, update that script or its methodology.txt and rerun it.
-- =============================================================================

/**
 * FX Volatility Surface Blueprints Artefact Population Script
 *
 * Registers the {METHODOLOGY} and the {DATASET_CODE}
 * dataset, and stages one SSVI blueprint for each of the {len(PAIRS)} pairs the derived
 * source quotes: {len(EXPIRIES) * len(LABELS)} pillars each, every pillar read from the
 * pair's derived series. The staged party and series ids are nil: the publish,
 * ores_refdata_publish_fx_vol_surface_blueprints_from_dq_fn, writes the system party
 * and the series it finds or creates. This script is idempotent.
 */

DO $$
BEGIN
    PERFORM ores_dq_methodologies_upsert_fn(ores_utility_system_tenant_id_fn(),
        {q(METHODOLOGY)},
        {q(METHODOLOGY_DESCRIPTION)},
        {q(METHODOLOGY_URL)},
        {q(steps)}
    );

    PERFORM ores_dq_datasets_upsert_fn(ores_utility_system_tenant_id_fn(),
        {q(DATASET_CODE)},
        'Synthetic Market Data',
        'Market Data',
        'Reference Data',
        'NONE',
        'Primary',
        'Synthetic',
        'Raw',
        {q(METHODOLOGY)},
        'FX Volatility Surface Blueprints',
        'The recipe the system calibrates each FX volatility surface by: one SSVI blueprint for each pair the derived source quotes, read from 1W to 1Y at ATM and the 25 and 10 delta risk reversals and butterflies.',
        'ORESTUDIO',
        'The surface blueprints provisioning copies to every party',
        current_date,
        'Internal Use Only',
        'fx_vol_surface_blueprints'
    );
END $$;

DO $$
declare
    v_dataset_id uuid;
    v_tenant_id uuid := ores_utility_system_tenant_id_fn();
begin
    select id into v_dataset_id
    from ores_dq_datasets_tbl
    where tenant_id = v_tenant_id
      and code = {q(DATASET_CODE)}
      and valid_to = ores_utility_infinity_timestamp_fn();

    if v_dataset_id is null then
        raise exception 'Dataset not found: {DATASET_CODE}';
    end if;

    delete from ores_dq_fx_vol_surface_blueprints_artefact_tbl where dataset_id = v_dataset_id;
    delete from ores_dq_fx_vol_surface_pillars_artefact_tbl where dataset_id = v_dataset_id;
    delete from ores_dq_fx_vol_surface_pillar_sources_artefact_tbl where dataset_id = v_dataset_id;

    insert into ores_dq_fx_vol_surface_blueprints_artefact_tbl (
        dataset_id, tenant_id, id, version, party_id, output_series_id, name,
        base_currency_code, quote_currency_code, fx_option_convention_id,
        smile_model, expiry_interpolation, output_expiries, output_strikes
    )
    values
{values(blueprint_lines)}

    insert into ores_dq_fx_vol_surface_pillars_artefact_tbl (
        dataset_id, tenant_id, id, version, party_id, blueprint_id, expiry_code, strike_label
    )
    values
{values(pillar_lines)}

    insert into ores_dq_fx_vol_surface_pillar_sources_artefact_tbl (
        dataset_id, tenant_id, id, version, party_id, pillar_id, market_series_id,
        contributor_code, weight
    )
    values
{values(source_lines)}
end $$;
"""


def main():
    with open(OUTPUT, "w") as handle:
        handle.write(script())
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()

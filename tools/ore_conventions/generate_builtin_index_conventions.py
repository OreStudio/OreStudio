"""Write the index conventions ORE defines in code as a populate script.

The input is =builtin_index_fields.tsv=, which =mine_builtin_conventions.py=
reads out of ORE itself: settlement days, fixing calendar, day counter,
business day convention, end of month and the oresmd address, one row per
family ORE builds when no convention defines the index.

A family that ORE builds both as an overnight index and as a term rate yields
two rows, one in each table: the kind is part of what the address means, and
the convention lookup picks by whether the index states a tenor.

    ./tools/ore_conventions/generate_builtin_index_conventions.py

The script is idempotent, like the hand-written populate scripts beside it.
"""


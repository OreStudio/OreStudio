def generate_staff_photos_populate():
    """One system-tenant image row per distinct face the staff use.

    The template is copied into a tenant and attached to the account by the
    attach_photos step, the same way Acme's staff photographs travel. The codes
    are Northwind's own, so the rows are this dataset's and not a second
    tenant's.
    """
    seen = {}
    for a in staff():
        key = a["photo_key"]
        if key in seen:
            continue
        face_file = key.split(":", 1)[1] + ".jpeg"
        with open(os.path.join(FACES_DIR, face_file), "rb") as f:
            seen[key] = base64.b64encode(f.read()).decode("ascii")

    statements = []
    for key, data_b64 in seen.items():
        image_id = uuid5("image:" + key)
        statements.append(f"""
    if not exists (
        select 1 from ores_assets_images_tbl
        where tenant_id = ores_utility_system_tenant_id_fn()
          and code = {sql_str(key)}
          and valid_to = ores_utility_infinity_timestamp_fn()
    ) then
        insert into ores_assets_images_tbl (
            id, tenant_id, version, code, description, mime_type, data,
            modified_by, performed_by, change_reason_code, change_commentary
        ) values (
            {sql_str(image_id)}, ores_utility_system_tenant_id_fn(), 0,
            {sql_str(key)},
            'Northwind Traders staff photo (facestudio synthetic faces)',
            'image/jpeg', {sql_str(data_b64)},
            current_user, current_user, 'system.external_data_import',
            'Northwind staff photo template'
        );
    end if;""")

    content = LICENSE_HEADER + GENERATED_NOTE + f"""
/**
 * Northwind Traders Staff Photo Templates
 *
 * One system-tenant template row per distinct facestudio face the staff use,
 * keyed by photo_key (e.g. "northwind_staff_photo:female_age25_european_01").
 * The attach_photos step copies a template into the tenant and attaches it to
 * the matching account. This script is idempotent.
 */

DO $$
BEGIN{"".join(statements)}
END $$;
"""
    write("northwind_staff_photos_populate.sql", content)



def q(value):
    return "'" + value.replace("'", "''") + "'"


def table_of(entity):
    """The table an entity's rows live in, as its model states it."""
    path = os.path.join(MODELING, f"ores.refdata.{entity}.org")
    if not os.path.exists(path):
        raise ValueError(f"{entity}: no model, so the map cannot name its table")
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if line.startswith(":tablename:"):
                return line.split(":", 2)[2].strip()
    raise ValueError(f"{entity}: the model states no tablename")


def rows():
    """One row per family column the projection reads, with its leaf."""
    derived, problems = sections.wiring(sections.source(), sections.leaves_of_schema())
    if problems:
        raise ValueError("\n".join(problems))
    found = {}
    entity_of = {}
    for section in derived:
        for parameter in section["parameters"]:
            entity = parameter["entity"]
            if entity == sections.DEFINITION_ENTITY:
                continue
            table = table_of(entity)
            if entity_of.setdefault(table, entity) != entity:
                raise ValueError(
                    f"{table}: {entity_of[table]} and {entity} share a table, but the"
                    " trigger carries one entity's name, so it cannot guard both")
            code = f"{entity}|{parameter['column']}"
            found[code] = {
                "code": code,
                "entity": entity,
                "column": parameter["column"],
                "table": table,
                "schema": sections.SCHEMA_NAME,
                "xpath": "/" + parameter["xpath"],
            }
    return [found[code] for code in sorted(found)]


def render_map(found):
    values = ",\n".join(
        "    (" + ", ".join([
            q(row["code"]), TENANT, "0", q(row["entity"]), q(row["column"]),
            q(row["table"]), q(row["schema"]), q(row["xpath"]), ACTOR,
            q("Seed the curve configuration columns"),
        ]) + ")" for row in found)
    return f"""{LICENCE}
/**
 * Curve Configuration Columns Population Script
 *
 * The columns of the curve family tables, and the ORE leaf each one holds.
 * Generated by projects/ores.sql/utility/generate_curve_column_guards.py from
 * the curve configuration projection and the ORE schema. Do not edit it by hand.
 * This script is idempotent.
 */

insert into ores_refdata_curve_configuration_columns_tbl (
    code, tenant_id, version, entity_name, column_name, table_name, schema_name,
    xpath, modified_by, change_reason_code, change_commentary
) values
{values}
on conflict (tenant_id, code)
where valid_to = ores_utility_infinity_timestamp_fn()
do nothing;

select 'Curve Configuration Columns' as entity, count(*) as count
from ores_refdata_curve_configuration_columns_tbl
where valid_to = ores_utility_infinity_timestamp_fn();
"""


def entity_of_table(found):
    """The entity each guarded table holds. One, because the map states one."""
    return {row["table"]: row["entity"] for row in found}


def render_guard(found):
    triggers = "\n".join(
        f"    execute format(\n"
        f"        'create or replace trigger %I before insert or update on %I '\n"
        f"        'for each row execute function ores_refdata_validate_curve_values_fn(%L)',\n"
        f"        '{TRIGGER}', '{table}', '{entity}');\n"
        for table, entity in sorted(entity_of_table(found).items()))
    return f"""{LICENCE}
/**
 * Curve Configuration Value Guard
 *
 * Refuses a value outside the set of the ORE leaf the column holds. One
 * enforcement point, in the database, because every writer passes through it: the
 * screen, a publish job and a shell script get the same answer from the same set.
 *
 * The map's child names each column's leaf, and the map row for that leaf's
 * address names its value set, so the answer comes from two tables and not from
 * the parameter contract, which a tenant may not have published. A column the map
 * does not name is not checked. Generated by
 * projects/ores.sql/utility/generate_curve_column_guards.py. Do not edit by hand.
 */

create or replace function ores_refdata_validate_curve_values_fn()
returns trigger
security definer
set search_path = public, pg_temp
as $$
declare
    v_row jsonb := to_jsonb(NEW);
    v_column record;
    v_value text;
begin
    for v_column in
        select k.column_name, m.value_set_code
          from ores_reporting_ore_element_map_columns_tbl k
          join ores_reporting_ore_parameter_vocabularies_tbl m
            on m.code = k.element_map_code
           and m.tenant_id = ores_utility_system_tenant_id_fn()
           and m.valid_to = ores_utility_infinity_timestamp_fn()
         where k.entity_name = TG_ARGV[0]
           and k.tenant_id = ores_utility_system_tenant_id_fn()
           and k.valid_to = ores_utility_infinity_timestamp_fn()
    loop
        v_value := v_row ->> v_column.column_name;
        if v_value is null or v_value = '' then
            continue;
        end if;
        if not ores_reporting_value_in_set_fn(v_column.value_set_code, v_value) then
            raise exception 'Invalid value % for %.%: the value is not in set %.',
                v_value, TG_ARGV[0], v_column.column_name, v_column.value_set_code;
        end if;
    end loop;
    return NEW;
end;
$$ language plpgsql;

/**
 * One trigger per family table. A table the map names that cannot be guarded
 * fails here, so no column is left unchecked by a quiet skip.
 */
do $$
begin
{triggers}end
$$;
"""


def render_drop(found):
    drops = "\n".join(
        f"drop trigger if exists {TRIGGER} on {table};"
        for table in sorted(entity_of_table(found)))
    return f"""{LICENCE}
/**
 * Drops the curve value guard triggers and their function. Generated by
 * projects/ores.sql/utility/generate_curve_column_guards.py.
 */

{drops}
drop function if exists ores_refdata_validate_curve_values_fn();
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if any committed file differs from the projection")
    args = parser.parse_args()
    found = rows()
    outputs = [(MAP, render_map(found)), (GUARD, render_guard(found)),
               (DROP, render_drop(found))]
    for path, content in outputs:
        if args.check:
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != content:
                print(f"{path} differs from the projection; regenerate it.", file=sys.stderr)
                return 1
        else:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(content)
    if args.check:
        print(f"{len(found)} curve columns map to their leaves.")
        return 0
    print(f"Wrote {MAP}, {GUARD} and {DROP}: {len(found)} columns")
    return 0


if __name__ == "__main__":
    sys.exit(main())

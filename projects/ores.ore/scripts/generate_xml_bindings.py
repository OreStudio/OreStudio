def local(tag):
    return tag.split("}")[-1] if "}" in tag else tag


def snake(name):
    step = re.sub(r"(?<=[A-Z])([A-Z])(?=[a-z])", r"_\1", name)
    step = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", step)
    return step.lower()


def hash_name(name):
    h = 2166136261
    for c in name:
        h ^= ord(c)
        h = (h * 16777619) & 0xFFFFFFFF
    return h


class Schema:
    def __init__(self, paths):
        self.complex_types = {}
        self.enumerations = {}
        self.simple_types = {}
        self.elements = {}
        for path in paths:
            root = ET.parse(path).getroot()
            for node in root.iter():
                name = node.get("name")
                if local(node.tag) == "complexType" and name:
                    self.complex_types[name] = node
                elif local(node.tag) == "simpleType" and name:
                    self.simple_types[name] = node
                    values = [
                        child.get("value")
                        for restriction in node
                        if local(restriction.tag) == "restriction"
                        for child in restriction
                        if local(child.tag) == "enumeration"
                    ]
                    if values:
                        self.enumerations[name] = values
                elif local(node.tag) == "element" and name:
                    self.elements.setdefault(name, node)
                    # An inline complexType is named after the element that
                    # carries it, which is the only name the schema gives it.
                    inline = [
                        child for child in node if local(child.tag) == "complexType"
                    ]
                    if inline:
                        self.complex_types.setdefault(name, inline[0])


def children_of(complex_type):
    """Elements and attributes of a complexType, in schema order."""
    elements, attributes = [], []
    for node in complex_type:
        if local(node.tag) in ("sequence", "all", "choice"):
            for element in node:
                if local(element.tag) == "element":
                    elements.append(element)
        elif local(node.tag) == "attribute":
            attributes.append(node)
    return elements, attributes


def is_residual(complex_type):
    for node in complex_type.iter():
        if local(node.tag) == "any":
            return True
    return False


def resolve_simple(schema, name, seen=None):
    """The primitive kind behind a named simpleType, or None.

    A simpleType that restricts another simpleType resolves through it. A
    simpleType with an enumeration is not a primitive: it is an enumeration,
    and the caller handles it first.
    """
    if name in PRIMITIVES:
        return PRIMITIVES[name]
    if name in schema.enumerations:
        return None
    node = schema.simple_types.get(name)
    if node is None:
        return None
    seen = seen or set()
    if name in seen:
        return None
    seen.add(name)
    for restriction in node:
        if local(restriction.tag) == "restriction":
            base = restriction.get("base")
            if base is not None:
                return resolve_simple(schema, base, seen)
    for union in node:
        if local(union.tag) == "union":
            members = (union.get("memberTypes") or "").split()
            for member in members:
                resolved = resolve_simple(schema, member, seen)
                if resolved is not None:
                    return resolved
    return None


def field_shape(schema, element):
    """The kind, scalar and nested type of one element."""
    declared = element.get("type")
    if declared in PRIMITIVES:
        return PRIMITIVES[declared], None
    if declared in schema.enumerations:
        return "enumeration", None
    if declared in schema.simple_types:
        kind = resolve_simple(schema, declared)
        return (kind or "text"), None
    if declared is not None:
        return "nested", declared
    # An inline complexType, which is what <xs:element name="X"><xs:complexType>
    # produces. The generator registered it under the element's name.
    if any(local(child.tag) == "complexType" for child in element):
        return "nested", element.get("name")
    raise SystemExit(f"element {element.get('name')} has neither a type nor a complexType")


def collect(schema, type_name, seen):
    """Type names reachable from `type_name`, in the order the schema reaches them.

    An ordered mapping rather than a set: the emission must be byte-identical
    on every run, and a set of strings iterates in an order that changes with
    the interpreter's hash seed.
    """
    if type_name in seen:
        return seen
    seen[type_name] = None
    complex_type = schema.complex_types.get(type_name)
    if complex_type is None:
        return seen
    elements, _ = children_of(complex_type)
    for element in elements:
        kind, nested = field_shape(schema, element)
        if kind == "nested" and nested is not None:
            collect(schema, nested, seen)
    return seen


def order_types(schema, root_type):
    seen = collect(schema, root_type, dict())
    ordered, done = [], set()

    def visit(name, stack):
        if name in done or name not in schema.complex_types:
            return
        if name in stack:
            raise SystemExit(f"recursive type {name} is not supported")
        stack.add(name)
        complex_type = schema.complex_types[name]
        elements, _ = children_of(complex_type)
        for element in elements:
            kind, nested = field_shape(schema, element)
            if kind == "nested" and nested is not None:
                visit(nested, stack)
        stack.discard(name)
        done.add(name)
        ordered.append(name)

    for name in seen:
        visit(name, set())
    return ordered


def member_declaration(schema, element, money):
    name = element.get("name")
    member = snake(name)
    repeated = element.get("maxOccurs") == "unbounded"
    declared = element.get("type")
    shape, _nested = field_shape(schema, element)

    if shape == "nested":
        return member, "nested", None, repeated
    if shape == "enumeration":
        kind, cpp = "enumeration", "std::int8_t"
    else:
        kind = shape
        cpp = CPP_TYPE[kind]
    if name in money:
        kind, cpp = "decimal", CPP_TYPE["decimal"]

    if repeated:
        return member, "repeated_leaf", f"std::vector<{cpp}>", True
    return member, kind, cpp, False


def render(schema, root_element, root_type, namespace, accessor, money, include):
    ordered = order_types(schema, root_type)
    header_name = accessor.replace("_document", "")

    declarations = []
    declares = []
    for type_name in ordered:
        complex_type = schema.complex_types[type_name]
        elements, attributes = children_of(complex_type)
        declares.append(f"struct {snake(type_name)};")
        body = [f"struct {snake(type_name)} {{", "    std::uint16_t present = 0;"]
        for attribute in attributes:
            body.append(f"    std::string {snake(attribute.get('name'))};")
        for element in elements:
            member, kind, cpp, repeated = member_declaration(schema, element, money)
            if kind == "nested":
                cpp = snake(element.get("type") or element.get("name"))
                if repeated:
                    cpp = f"std::vector<{cpp}>"
            body.append(f"    {cpp} {member};")
        if is_residual(complex_type):
            body.append("    std::vector<residual_element> extras;")
        body.append("};")
        declarations.append("\n".join(body))

    tables = []
    for type_name in ordered:
        complex_type = schema.complex_types[type_name]
        elements, attributes = children_of(complex_type)
        rows = []
        bit = 0
        for attribute in attributes:
            name = attribute.get("name")
            required = attribute.get("use") == "required"
            rows.append(
                f'    {{"{name}", {hash_name(name)}u, field_kind::text, '
                f"std::uint16_t(offsetof({snake(type_name)}, {snake(name)})), {bit}, true, "
                f"{'true' if required else 'false'}, nullptr, nullptr, "
                f"scalar_kind::text, nullptr}},"
            )
            bit += 1
        for element in elements:
            name = element.get("name")
            member, kind, cpp, repeated = member_declaration(schema, element, money)
            required = element.get("minOccurs", "1") != "0"
            scalar = SCALAR.get(kind, "scalar_kind::text")
            if kind == "nested":
                field_kind = "repeated_nested" if repeated else "nested"
                nested = snake(element.get("type") or element.get("name"))
                append = f"&append_to<{nested}>" if repeated else "nullptr"
                rows.append(
                    f'    {{"{name}", {hash_name(name)}u, field_kind::{field_kind}, '
                    f"std::uint16_t(offsetof({snake(type_name)}, {member})), {bit}, false, "
                    f"{'true' if required else 'false'}, nullptr, "
                    f"&{nested}_type, scalar_kind::text, {append}}},"
                )
            else:
                tokens = (
                    f"{snake(element.get('type'))}_spellings"
                    if kind == "enumeration"
                    else "nullptr"
                )
                rows.append(
                    f'    {{"{name}", {hash_name(name)}u, field_kind::{kind}, '
                    f"std::uint16_t(offsetof({snake(type_name)}, {member})), {bit}, false, "
                    f"{'true' if required else 'false'}, {tokens}, nullptr, {scalar}, nullptr}},"
                )
            bit += 1
        if is_residual(complex_type):
            rows.append(
                f'    {{"", 0u, field_kind::residual, '
                f"std::uint16_t(offsetof({snake(type_name)}, extras)), "
                f"{bit}, false, false, nullptr, nullptr, scalar_kind::text, nullptr}},"
            )
            bit += 1
        tables.append(
            f"const field {snake(type_name)}_fields[] = {{\n"
            + "\n".join(rows)
            + f"\n}};\nconst record_type {snake(type_name)}_type{{\"{type_name}\", "
            f"{snake(type_name)}_fields, {bit}}};"
        )

    spellings = []
    emitted = set()
    for type_name in ordered:
        for element in children_of(schema.complex_types[type_name])[0]:
            declared = element.get("type")
            if declared in schema.enumerations and declared not in emitted:
                emitted.add(declared)
                values = ", ".join(f'"{v}"' for v in schema.enumerations[declared])
                spellings.append(
                    f"const char* {snake(declared)}_spellings[] = {{{values}, nullptr}};"
                )

    header = f'''{LICENCE}#ifndef {header_name.upper()}_HPP
#define {header_name.upper()}_HPP

#include "ores.ore.core/xml/binding.hpp"
#include "ores.utility/decimal/decimal.hpp"

#include <cstdint>
#include <string>
#include <vector>

namespace {namespace} {{

{chr(10).join(declares)}

{chr(10).join(declarations)}

ORES_ORE_CORE_EXPORT auto {accessor}() -> const document_type&;

}}

#endif
'''

    source = f'''{LICENCE}#include "{include}"

#include <cstddef>

namespace {namespace} {{

namespace {{

template <typename T>
auto append_to(void* container, void** slot) -> void {{
    auto* vector = static_cast<std::vector<T>*>(container);
    vector->emplace_back();
    *slot = &vector->back();
}}

{chr(10).join(spellings)}

{chr(10).join(tables)}

}}

ORES_ORE_CORE_EXPORT auto {accessor}() -> const document_type& {{
    static const document_type doc{{"{root_element}", &{snake(root_type)}_type}};
    return doc;
}}

}}
'''
    return header, source


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", action="append", required=True)
    parser.add_argument("--root-element", required=True)
    parser.add_argument("--root-type", required=True)
    parser.add_argument("--namespace", default="ores::ore::xml::generated")
    parser.add_argument("--accessor", required=True)
    parser.add_argument("--include", default="")
    parser.add_argument("--header", required=True)
    parser.add_argument("--source", required=True)
    parser.add_argument(
        "--money",
        action="append",
        default=[],
        help="element name to treat as an exact decimal regardless of its schema type",
    )
    args = parser.parse_args()

    schema = Schema(args.schema)
    if args.root_type not in schema.complex_types:
        raise SystemExit(f"no complexType {args.root_type}")
    default_include = "ores.ore.core/xml/" + args.accessor.replace("_document", "") + ".hpp"
    header, source = render(
        schema,
        args.root_element,
        args.root_type,
        args.namespace,
        args.accessor,
        set(args.money),
        args.include or default_include,
    )
    with open(args.header, "w", encoding="utf-8") as handle:
        handle.write(header)
    with open(args.source, "w", encoding="utf-8") as handle:
        handle.write(source)
    sys.stderr.write(f"wrote {args.header} and {args.source}\n")


if __name__ == "__main__":
    main()

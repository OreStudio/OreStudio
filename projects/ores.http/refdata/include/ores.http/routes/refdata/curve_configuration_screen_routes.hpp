#ifndef ORES_HTTP_ROUTES_REFDATA_CURVE_CONFIGURATION_SCREEN_ROUTES_HPP
#define ORES_HTTP_ROUTES_REFDATA_CURVE_CONFIGURATION_SCREEN_ROUTES_HPP

#include "ores.http.api/net/router.hpp"
#include "ores.http.api/openapi/endpoint_registry.hpp"
#include "ores.nats/service/nats_client.hpp"
#include <memory>

namespace ores::http::routes::refdata {

/**
 * @brief A party's curve configurations, as the curve configuration screen reads
 * them.
 *
 * A configuration is a header row and the definitions that hang off it, and the
 * screen counts a configuration's curves and the sections they name before
 * anybody opens one, so the page gives a person a way in without a report that
 * binds it.
 */
class curve_configuration_screen_routes final {
public:
    /// Register the reads and the write of the curve configuration screen.
    static void register_routes(std::shared_ptr<ores::http::net::router> router,
                                std::shared_ptr<ores::http::openapi::endpoint_registry> registry,
                                ores::nats::service::nats_client& session);
};

}

#endif

def by_company(records):
    grouped = {c: [] for c in COMPANIES}
    for r in records:
        grouped.setdefault(r["company_code"], []).append(r)
    return grouped


def main():
    lei_entities = load("lei_entities")
    lei_relationships = load("lei_relationships")
    business_units = by_company(load("business_units"))
    portfolios = by_company(load("portfolios"))
    books = by_company(load("books"))
    accounts = by_company(load("accounts"))
    netting_agreements = by_company(load("netting_agreements"))
    netting_sets = by_company(load("netting_sets"))
    csas = by_company(load("csas"))

    generate_catalog_populate()
    generate_dataset_populate(COMPANIES)
    generate_lei_entities_populate(lei_entities)
    generate_lei_relationships_populate(lei_relationships)
    generate_staff_photos_populate(
        [a for company in COMPANIES for a in accounts[company]] + accounts["acme_group"])
    for company in COMPANIES:
        generate_business_units_populate(company, business_units[company])
        generate_portfolios_populate(company, portfolios[company], business_units[company])
        generate_books_populate(company, books[company], portfolios[company])
        generate_accounts_populate(company, accounts[company])
        generate_account_contact_informations_populate(company, accounts[company])

    # Group-level: accounts and their contact details (just the fixed CEO
    # account) plus the holding company's own Group
    # Treasury business unit/portfolio/books, scoped to the holding
    # company's own party.
    generate_accounts_populate("acme_group", accounts["acme_group"])
    generate_account_contact_informations_populate(
        "acme_group", accounts["acme_group"])
    generate_business_units_populate("acme_group", business_units["acme_group"])
    generate_portfolios_populate(
        "acme_group", portfolios["acme_group"], business_units["acme_group"])
    generate_books_populate("acme_group", books["acme_group"], portfolios["acme_group"])

    for company in NETTING_COMPANIES:
        generate_netting_agreements_populate(company, netting_agreements[company])
        generate_netting_sets_populate(company, netting_sets[company])
        generate_csas_populate(company, csas[company])



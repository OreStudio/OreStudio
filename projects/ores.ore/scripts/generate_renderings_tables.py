"""Write the tables ORE's reader converts with, from the authored renderings.

The renderings live in =ore_renderings.json=: the form a configuration holds,
and every other rendering that means it. The value sets read that file directly.
The reader in C++ cannot, so its tables are written from the file here.

The file is the authority. A table the file does not state is a row the value
sets can offer and the reader cannot convert, so --check fails when the two
disagree. It also fails when the reader states a table of its own, because that
is a second authority over the same fact.

    generate_renderings_tables.py          write the header
    generate_renderings_tables.py --check  fail if the committed header differs
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "..", "..", ".."))
RENDERINGS = os.path.join(ROOT, "projects", "ores.sql", "utility", "ore_renderings.json")
HEADER = os.path.join(ROOT, "projects", "ores.ore", "core", "src", "domain",
                      "conventions_renderings.hpp")
READER = os.path.join(ROOT, "projects", "ores.ore", "core", "src", "domain",
                      "conventions_fields.cpp")

GUARD = "ORES_ORE_CORE_SRC_DOMAIN_CONVENTIONS_RENDERINGS_HPP"

LICENCE = """/* -*- mode: c++; tab-width: 4; indent-tabs-mode: nil; c-basic-offset: 4 -*-
 *
 * Copyright (C) 2026 Marco Craveiro <marco.craveiro@gmail.com>
 *
 * This program is free software; you can redistribute it and/or modify it under
 * the terms of the GNU General Public License as published by the Free Software
 * Foundation; either version 3 of the License, or (at your option) any later
 * version.
 *
 * This program is distributed in the hope that it will be useful, but WITHOUT
 * ANY WARRANTY; without even the implied warranty of MERCHANTABILITY or FITNESS
 * FOR A PARTICULAR PURPOSE. See the GNU General Public License for more
 * details.
 *
 * You should have received a copy of the GNU General Public License along with
 * this program; if not, write to the Free Software Foundation, Inc., 51
 * Franklin Street, Fifth Floor, Boston, MA 02110-1301, USA.
 *
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by generate_renderings_tables.py from ore_renderings.json.
 */
"""

TABLE = re.compile(r"const code_table (\w+) = \{")


def read_tables():
    """The canonical form of each rendering, by table, in the order the file states."""
    with open(RENDERINGS, encoding="utf-8") as handle:
        return json.load(handle)["tables"]


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(tables):
    out = [LICENCE, f"#ifndef {GUARD}\n#define {GUARD}\n",
           '#include "conventions_fields.hpp"\n',
           "namespace ores::ore::domain::conventions_fields {\n"]
    for name, groups in tables.items():
        out.append(f"const code_table {name} = {{")
        for canonical, renderings in groups.items():
            for rendering in renderings:
                out.append(f"    {{{quote(rendering)}, {quote(canonical)}}},")
        out.append("};\n")
    out.append("}\n\n#endif\n")
    return "\n".join(out)


def committed():
    if not os.path.exists(HEADER):
        return ""
    with open(HEADER, encoding="utf-8") as handle:
        return handle.read()


def check(content):
    problems = []
    if committed() != content:
        problems.append(f"{os.path.relpath(HEADER, ROOT)} differs from "
                        f"{os.path.relpath(RENDERINGS, ROOT)}")
    with open(READER, encoding="utf-8") as handle:
        reader = handle.read()
    for name in TABLE.findall(reader):
        problems.append(f"{os.path.relpath(READER, ROOT)} states a {name} table of its own")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed header differs from the file")
    args = parser.parse_args()
    tables = read_tables()
    content = render(tables)
    if args.check:
        problems = check(content)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print("Run ./projects/ores.ore/scripts/generate_renderings_tables.py "
                  "and commit the header.", file=sys.stderr)
            return 1
        forms = sum(len(groups) for groups in tables.values())
        print(f"{forms} canonical forms across {len(tables)} tables match "
              f"{os.path.relpath(RENDERINGS, ROOT)}.")
        return 0
    with open(HEADER, "w", encoding="utf-8") as handle:
        handle.write(content)
    print(f"Wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

def register_substitutes(schema, root):
    """Map each substitution group head to the elements that stand in for it."""
    globals_by_name = {}
    for node in root:
        if local(node.tag) == "element" and node.get("name"):
            globals_by_name[node.get("name")] = node
    for node in root.iter():
        if local(node.tag) != "element":
            continue
        group = node.get("substitutionGroup")
        if group is not None:
            schema.substitutes.setdefault(group, []).append(node)
    for name_, node_ in globals_by_name.items():
        held = schema.globals.get(name_)
        if held is not None and held.get("type") != node_.get("type") and (
            node_.get("type") is not None or held.get("type") is not None
        ):
            raise SystemExit(
                f"two schemas declare a global element named {name_} with different types"
            )
        schema.globals.setdefault(name_, node_)


def register_inline(schema, root):
    """Give every inline complexType a unique name, after its element."""
    parents = {child: node for node in root.iter() for child in node}
    for node in root.iter():
        if local(node.tag) != "element":
            continue
        inline = [child for child in node if local(child.tag) == "complexType"]
        if not inline:
            continue
        chosen = node.get("name")
        owner = parents.get(node)
        while chosen in schema.complex_types and schema.complex_types[chosen] is not inline[0]:
            enclosing = owner.get("name") if owner is not None else None
            chosen = f"{enclosing}_{chosen}" if enclosing else chosen + "_type"
            owner = parents.get(owner) if owner is not None else None
        schema.complex_types.setdefault(chosen, inline[0])
        schema.inline_name[id(node)] = chosen


def local(tag):
    return tag.split("}")[-1] if "}" in tag else tag


def clone_with_identity(schema, node):
    """A copy of a schema node that keeps the inline identity of the original.

    A group or a substitution member is referenced from more than one type, and
    each reference states its own cardinality. The node is copied so a reference
    cannot change what the next one reads, and the names the generator gave the
    original's inline types are carried to the copy, because they are keyed by
    element identity.
    """
    duplicate = copy.deepcopy(node)
    schema.clones.append(duplicate)

    def transfer(original, cloned):
        if id(original) in schema.inline_name:
            schema.inline_name[id(cloned)] = schema.inline_name[id(original)]
        if id(original) in schema.inline_enum:
            schema.inline_enum[id(cloned)] = schema.inline_enum[id(original)]
        for left, right in zip(list(original), list(cloned)):
            transfer(left, right)

    transfer(node, duplicate)
    return duplicate


def snake(name):
    step = re.sub(r"(?<=[A-Z])([A-Z])(?=[a-z])", r"_\1", name)
    step = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", step)
    return step.lower()


def hash_name(name):
    h = 2166136261
    for c in name:
        h ^= ord(c)
        h = (h * 16777619) & 0xFFFFFFFF
    return h


class Schema:
    def __init__(self, paths):
        self.complex_types = {}
        self.enumerations = {}
        self.simple_types = {}
        self.elements = {}
        # An inline complexType is named after its element, and ORE reuses
        # element names across families: two different types are both called
        # Correlation. The first keeps the plain name and the rest are
        # qualified by the type that holds them.
        self.inline_name = {}
        # An abstract element with substitution members is one position in the
        # schema and several element names in a document: a choice. Each member
        # becomes its own optional field, which is how the model states a
        # variation without a polymorphic payload.
        self.substitutes = {}
        # A model group written once and referenced by name: its members are
        # flattened where it is referenced, which is what a record does with a
        # group.
        self.groups = {}
        # The global elements of every schema read, by name. A reference names
        # one of them, and the schemas are read in a list, so the index is
        # accumulated rather than replaced per file.
        self.globals = {}
        # The (holder, member) pairs whose type closes a cycle. A record cannot
        # hold itself, so those members are left out and a document that states
        # one is refused by the reading.
        self.cut_members = set()
        # The types a document can reach after the cut edges are left out.
        self.used_types = set()
        # The node copies a group or a reference makes, held so their ids stay
        # unique for the whole run: the inline tables are keyed by identity.
        self.clones = []
        # An inline simpleType is an enumeration with no name of its own. Its
        # spellings are emitted under the type that holds it.
        self.inline_enum = {}
        for path in paths:
            root = ET.parse(path).getroot()
            register_inline(self, root)
            register_substitutes(self, root)
            for node in root.iter():
                name = node.get("name")
                if local(node.tag) == "complexType" and name:
                    self.complex_types[name] = node
                elif local(node.tag) == "simpleType" and name:
                    self.simple_types[name] = node
                    values = [
                        child.get("value")
                        for restriction in node
                        if local(restriction.tag) == "restriction"
                        for child in restriction
                        if local(child.tag) == "enumeration"
                    ]
                    if values:
                        self.enumerations[name] = values
                elif local(node.tag) == "group" and name:
                    self.groups.setdefault(name, node)
                elif local(node.tag) == "element" and name:
                    self.elements.setdefault(name, node)


# The presence mask is one word per 64 fields. A type with more fields than one
# word holds states its mask as an array, and the engine indexes the word a
# field's bit falls in. The bound below is only a sanity limit.
MASK_WORD_BITS = 64
# A field's bit and a record's field count are std::uint8_t in the table, so 255
# fields is the ceiling whatever the mask could say.
MAX_MASK_BITS = 255

# Elements that are alternatives inside an xs:choice. At most one of them
# appears per iteration, so none is individually required however the schema
# writes its minOccurs.
CHOICE_CHILDREN = set()


def simple_content_base(complex_type):
    """The base type of an xs:simpleContent extension, or None.

    An element written this way carries text of its own beside its attributes,
    which is a different shape from every other leaf: the text belongs to the
    element, and the attributes sit on the same record.
    """
    for node in complex_type:
        if local(node.tag) != "simpleContent":
            continue
        for extension in node:
            if local(extension.tag) == "extension":
                return extension.get("base")
    return None


UNSUPPORTED = ("attributeGroup", "anyAttribute")


def _collect_children(nodes, schema, complex_type, elements, attributes, bases):
    """Walks the nodes of one content model into the two lists.

    `bases` is the chain of types this walk has already flattened, so a
    derivation that reaches itself is refused instead of recursing.
    """
    def walk(node, repeat_max=None, in_choice=False, optional=False, groups=frozenset()):
        name = local(node.tag)
        if name == "annotation":
            return
        if name == "group":
            reference = node.get("ref")
            definition = schema.groups.get(reference) if schema is not None else None
            if definition is None:
                raise SystemExit(
                    f"they type {complex_type.get('name')} references the group {reference}, "
                    "which is not a group this generator read"
                )
            if reference in groups:
                raise SystemExit(
                    f"they type {complex_type.get('name')} references the group {reference} "
                    "in a cycle"
                )
            own = node.get("maxOccurs", "1")
            if own not in ("1",):
                repeat_max = own
            optional = optional or node.get("minOccurs", "1") == "0"
            for child in definition:
                cloned = clone_with_identity(schema, child)
                if repeat_max is not None and cloned.get("maxOccurs", "1") in ("1",):
                    cloned.set("maxOccurs", repeat_max)
                walk(cloned, repeat_max, in_choice, optional, groups | {reference})
            return
        if name in ("sequence", "all", "choice"):
            # A compositor that repeats repeats its members: a document may
            # carry any member of a repeated choice any number of times, and
            # the member's own maxOccurs says nothing about that. One that is
            # optional makes its members optional, because the whole group may
            # be absent. A compositor nested in another is walked through,
            # because a choice whose alternatives are sequences still offers
            # each of their elements as a child of the type.
            own = node.get("maxOccurs", "1")
            if own not in ("1",):
                repeat_max = own
            optional = optional or node.get("minOccurs", "1") == "0"
            alternatives = in_choice or name == "choice"
            for child in node:
                walk(child, repeat_max, alternatives, optional, groups)
            return
        if name == "element":
            if repeat_max is not None and node.get("maxOccurs", "1") in ("1",):
                node.set("maxOccurs", repeat_max)
            if optional and node.get("minOccurs", "1") != "0":
                node.set("minOccurs", "0")
            elements.append(node)
            if in_choice:
                CHOICE_CHILDREN.add(id(node))
            return
        if name == "attribute":
            attributes.append(node)
            return
        if name == "simpleContent":
            for extension in node:
                if local(extension.tag) != "extension":
                    continue
                for child in extension:
                    walk(child)
            return
        if name == "complexContent":
            if schema is None:
                raise SystemExit(
                    f"they type {complex_type.get('name')} uses xs:complexContent, which needs"
                    " the schema to resolve"
                )
            for derivation in node:
                kind_name = local(derivation.tag)
                if kind_name == "restriction":
                    raise SystemExit(
                        f"they type {complex_type.get('name')} restricts a base type, which is"
                        " not supported"
                    )
                if kind_name != "extension":
                    continue
                base = derivation.get("base")
                base_type = schema.complex_types.get(base)
                if base_type is None:
                    raise SystemExit(
                        f"they type {complex_type.get('name')} extends {base}, which is not a"
                        " complexType this generator read"
                    )
                if base in bases:
                    raise SystemExit(
                        f"they type {complex_type.get('name')} derives from {base} in a cycle"
                    )
                base_elements, base_attributes = children_of(base_type, schema, bases | {base})
                elements.extend(base_elements)
                attributes.extend(base_attributes)
                for child in derivation:
                    walk(child)
            return
        if name in UNSUPPORTED or name == "annotation":
            # Attribute groups and wildcard attributes are shapes this
            # generator does not read. Emitting nothing for them would produce a
            # table that silently disagrees with the schema, so they stop the
            # run instead.
            raise SystemExit(
                f"they type {complex_type.get('name')} uses xs:{name}, which is not supported"
            )

    for node in nodes:
        walk(node)


def children_of(complex_type, schema=None, bases=frozenset()):
    """Elements and attributes of a complexType, in schema order.

    A type written as xs:complexContent extension is the base type's children
    followed by its own: the derived record holds both, in the order the
    document writes them, and the base keeps its own record as well.
    """
    elements, attributes = [], []
    _collect_children(complex_type, schema, complex_type, elements, attributes, bases)

    # Two alternatives of one choice may name the same element. The record
    # needs one member for it, and a document that writes either alternative
    # binds to that member, so the second declaration is dropped when the two
    # agree. They are refused when they do not: one member cannot mean two
    # shapes.
    def shape(element):
        """What a document sees of one element: name, type, cardinality, inline shape.

        A `ref` names a global element, so the name and type come from there
        while the cardinality stays on the reference. An element that writes its
        own type has no type name of its own, so the inline type's generated
        name and its spellings stand in for it.
        """
        reference = element.get("ref")
        target = element if reference is None else schema.elements.get(reference, element)
        # An element written with its own type has no `type` attribute, so the
        # name the generator gave that inline type stands in for its shape. Two
        # alternatives that each write a different inline type therefore do not
        # agree, however many children each happens to have.
        inline = schema.inline_name.get(id(target))
        return (
            reference or target.get("name"),
            target.get("type") or inline,
            element.get("minOccurs"),
            element.get("maxOccurs"),
            tuple(schema.inline_enum.get(id(target), ())),
        )

    first_by_key, kept = {}, []
    for element in elements:
        key = shape(element)[0]
        first = first_by_key.get(key)
        if first is None:
            first_by_key[key] = element
            kept.append(element)
            continue
        both_choice = id(element) in CHOICE_CHILDREN and id(first) in CHOICE_CHILDREN
        if both_choice and shape(element) == shape(first):
            continue
        kept.append(element)
    elements = kept

    # A projection looks a member up by the name the document writes, and the
    # document does not say whether it is an element or an attribute. A type
    # that spelled both the same would make that lookup ambiguous, so it is
    # refused here rather than resolved silently later.
    element_names = [element.get("name") or element.get("ref") for element in elements]
    attribute_names = [attribute.get("name") for attribute in attributes]
    # A name the base already holds, or the same name as both an element and an
    # attribute, would give the record two members at different offsets and the
    # projection one name for two rows. Both are refused here.
    for name in element_names:
        if element_names.count(name) > 1:
            raise SystemExit(f"{complex_type.get('name')} holds two elements named {name!r}")
        if name in attribute_names:
            raise SystemExit(
                f"{complex_type.get('name')} declares both an element and an attribute "
                f"named {name!r}"
            )
    for name in attribute_names:
        if attribute_names.count(name) > 1:
            raise SystemExit(f"{complex_type.get('name')} holds two attributes named {name!r}")
    return elements, attributes


def resolve_enumeration(schema, name, seen=None):
    """The enumerated simpleType behind a name, following restrictions.

    A simpleType may restrict another simpleType any number of times, and a
    xs:simpleContent base may name any link in that chain. The spellings belong
    to the link that declares them, so the walk returns that name rather than
    the alias the base names.
    """
    seen = seen or set()
    if name is None or name in seen:
        return None
    seen.add(name)
    if name in schema.enumerations:
        return name
    node = schema.simple_types.get(name)
    if node is None:
        return None
    for restriction in node:
        if local(restriction.tag) != "restriction":
            continue
        resolved = resolve_enumeration(schema, restriction.get("base"), seen)
        if resolved is not None:
            return resolved
    return None


def content_kind(schema, complex_type):
    """The primitive kind of an element's own text, or None."""
    base = simple_content_base(complex_type)
    if base is None:
        return None
    if resolve_enumeration(schema, base) is not None:
        return "enumeration"
    if base in PRIMITIVES:
        return PRIMITIVES[base]
    resolved = resolve_simple(schema, base)
    return resolved or "text"


def content_enumeration(schema, complex_type):
    """The enumerated simpleType an element's own text is written as, or None.

    A type written as xs:simpleContent extension inherits its text from a base
    simpleType, and the base may be an enumeration. The text is then one of the
    base's spellings, which the table states so the reading refuses a spelling
    the schema does not allow.
    """
    return resolve_enumeration(schema, simple_content_base(complex_type))


def is_residual(complex_type):
    for node in complex_type.iter():
        if local(node.tag) == "any":
            return True
    return False


def resolve_simple(schema, name, seen=None):
    """The primitive kind behind a named simpleType, or None.

    A simpleType that restricts another simpleType resolves through it. A
    simpleType with an enumeration is not a primitive: it is an enumeration,
    and the caller handles it first.
    """
    if name in PRIMITIVES:
        return PRIMITIVES[name]
    if name in schema.enumerations:
        return None
    node = schema.simple_types.get(name)
    if node is None:
        return None
    seen = seen or set()
    if name in seen:
        return None
    seen.add(name)
    for restriction in node:
        if local(restriction.tag) == "restriction":
            base = restriction.get("base")
            if base is not None:
                return resolve_simple(schema, base, seen)
    for union in node:
        if local(union.tag) == "union":
            members = (union.get("memberTypes") or "").split()
            for member in members:
                resolved = resolve_simple(schema, member, seen)
                if resolved is not None:
                    return resolved
    return None


def inline_simple(schema, element):
    """The values of an element's inline simpleType, if it has one."""
    for child in element:
        if local(child.tag) != "simpleType":
            continue
        values = [
            enumeration.get("value")
            for restriction in child
            if local(restriction.tag) == "restriction"
            for enumeration in restriction
            if local(enumeration.tag) == "enumeration"
        ]
        if values:
            return values
        for restriction in child:
            if local(restriction.tag) == "restriction":
                base = restriction.get("base")
                if base is not None:
                    return resolve_simple(schema, base)
    return None


def field_shape(schema, element):
    """The kind, scalar and nested type of one element."""
    inline = inline_simple(schema, element)
    if isinstance(inline, list):
        schema.inline_enum[id(element)] = inline
        return "enumeration", None
    if isinstance(inline, str):
        return inline, None

    declared = element.get("type")
    if declared in PRIMITIVES:
        return PRIMITIVES[declared], None
    if declared is not None and declared.startswith("xs:"):
        # An XML Schema built-in the table above does not name. It is a scalar
        # whatever it is, never a record.
        return "text", None
    if declared in schema.enumerations:
        return "enumeration", None
    if declared in schema.simple_types:
        kind = resolve_simple(schema, declared)
        return (kind or "text"), None
    if declared is not None:
        return "nested", declared
    # An inline complexType, which is what <xs:element name="X"><xs:complexType>
    # produces. The generator registered it, possibly under a qualified name.
    if any(local(child.tag) == "complexType" for child in element):
        return "nested", schema.inline_name[id(element)]
    if declared is None and not any(local(child.tag) == "simpleType" for child in element):
        # An element with no type at all is xs:anyType, which the schema does
        # not describe. It is carried as text: a document that puts children in
        # it is refused by the reading rather than half stored.
        return "text", None
    raise SystemExit(f"element {element.get('name')} has neither a type nor a complexType")


def collect(schema, type_name, seen):
    """Type names reachable from `type_name`, in the order the schema reaches them.

    An ordered mapping rather than a set: the emission must be byte-identical
    on every run, and a set of strings iterates in an order that changes with
    the interpreter's hash seed.
    """
    if type_name in seen:
        return seen
    seen[type_name] = None
    complex_type = schema.complex_types.get(type_name)
    if complex_type is None:
        return seen
    for node in complex_type:
        if local(node.tag) != "complexContent":
            continue
        for derivation in node:
            base = derivation.get("base")
            if base is not None:
                collect(schema, base, seen)
    elements, _ = children_of(complex_type, schema)
    for element in elements:
        for field in expand(schema, element):
            kind, nested = field_shape(schema, field)
            if kind == "nested" and nested is not None:
                collect(schema, nested, seen)
    return seen


def nested_target(schema, field):
    """The complex type a member holds, or None when it holds a value."""
    kind, target = field_shape(schema, field)
    if kind != "nested" or target is None:
        return None
    return target


def order_types(schema, root_type):
    """The types a record can hold, dependencies first.

    A record is a fixed layout, so a type is defined before the type that holds
    it, and no type holds itself. An edge that closes a cycle is recorded in
    schema.cut_members and emitted as an index row into an arena the holder
    owns, so the record holds the member without holding its type.
    """
    reachable = collect(schema, root_type, dict())
    edges = {}
    for name in reachable:
        complex_type = schema.complex_types.get(name)
        if complex_type is None:
            continue
        targets = []
        elements, _ = children_of(complex_type, schema)
        for element in elements:
            for field in expand(schema, element):
                target = nested_target(schema, field)
                if target is not None and target in schema.complex_types:
                    targets.append((snake(field.get("name")), target))
        edges[name] = targets

    cut, ordered, done = set(), [], set()

    def visit(name, stack):
        if name in done or name not in schema.complex_types:
            return
        stack.add(name)
        for member, target in edges.get(name, ()):
            if target in stack:
                cut.add((name, member, target))
                continue
            visit(target, stack)
        stack.discard(name)
        done.add(name)
        ordered.append(name)

    visit(root_type, set())
    for name in reachable:
        visit(name, set())
    schema.cut_members = cut

    used = set()

    def mark(name):
        if name in used or name not in schema.complex_types:
            return
        used.add(name)
        for _member, target in edges.get(name, ()):
            mark(target)

    mark(root_type)
    schema.used_types = used
    return ordered


def expand(schema, element):
    """The fields one schema element produces.

    Normally one. A reference to an abstract element with substitution members
    produces one per member, each optional, because only one of them appears in
    any given document and the model states that as a variation rather than as
    a polymorphic payload.
    """
    ref = element.get("ref")
    if ref is None:
        yield element
        return
    members = schema.substitutes.get(ref)
    head = schema.globals.get(ref)
    if members:
        for member in members:
            # Exactly one member appears in any document, so each is optional
            # regardless of the cardinality written on the reference. The member
            # itself is yielded rather than a copy: a member that writes its own
            # type carries it inline, and the generator names inline types by
            # element identity, so the member itself is used rather than a copy.
            stand_in = clone_with_identity(schema, member)
            stand_in.set("minOccurs", "0")
            stand_in.set("maxOccurs", element.get("maxOccurs", "1"))
            yield stand_in
        return
    if head is not None and head.get("type") is None and id(head) in schema.inline_name:
        # A member of another group may be referenced by name. It carries its
        # type inline, so it is yielded as itself for the same reason.
        head = clone_with_identity(schema, head)
        head.set("minOccurs", element.get("minOccurs", "1"))
        head.set("maxOccurs", element.get("maxOccurs", "1"))
        yield head
        return
    if head is not None and head.get("type") is not None:
        # A plain global element: synthesise the element that names it.
        stand_in = ET.Element("xs:element")
        stand_in.set("name", ref)
        stand_in.set("type", head.get("type"))
        stand_in.set("minOccurs", element.get("minOccurs", "1"))
        stand_in.set("maxOccurs", element.get("maxOccurs", "1"))
        yield stand_in
        return
    detail = "no such global element"
    if head is not None:
        detail = "the global element states no type"
    raise SystemExit(f"element reference {ref} cannot be resolved: {detail}")


def spellings_of(schema, owner, element):
    """The spelling table a field points at, or None."""
    if id(element) in schema.inline_enum:
        return f"{snake(owner)}_{snake(element.get('name'))}_spellings"
    declared = element.get("type")
    if declared in schema.enumerations:
        return f"{snake(declared)}_spellings"
    return None


def ops_name(type_name, member):
    """The table entry that grows, measures and indexes one repeated member."""
    return f"{type_name}_{member}_ops"


def vector_element_type(cpp):
    prefix = "std::vector<"
    if not cpp.startswith(prefix):
        raise SystemExit(f"{cpp} is not a vector of one element type")
    return cpp[len(prefix) : -1]


# A record that holds this many members, counting the records it holds by value,
# is wide: moving one costs more than the work of reading it. Repeated children
# of a wide record sit in a std::deque, which never moves an element, instead of
# a std::vector, which moves every element each time it grows. The widest record
# below the line holds 454 members and the narrowest above it holds 10,837, so
# the value does not sit on a boundary.
WIDE_RECORD_MEMBERS = 1000


def member_counts(schema, emitted, names, cut, exact_decimals):
    """How many members each emitted record holds, records held by value included."""
    own = {}
    held = {}
    for type_name in emitted:
        complex_type = schema.complex_types[type_name]
        elements, attributes = children_of(complex_type, schema)
        count = len(attributes)
        if content_kind(schema, complex_type) is not None:
            count += 1
        if is_residual(complex_type):
            count += 1
        by_value = []
        for element in elements:
            for field in expand(schema, element):
                _member, kind, _cpp, repeated = member_declaration(schema, field, exact_decimals)
                if kind != "nested":
                    count += 1
                    continue
                target = field.get("type") or schema.inline_name.get(id(field), field.get("name"))
                if repeated or (type_name, snake(field.get("name"))) in cut or target not in names:
                    # A vector, or an arena and its index row, is a few words.
                    count += 1
                else:
                    by_value.append(target)
        own[type_name] = count
        held[type_name] = by_value

    totals = {}

    def total(type_name):
        if type_name not in totals:
            totals[type_name] = own[type_name] + sum(total(t) for t in held[type_name] if t in own)
        return totals[type_name]

    return {type_name: total(type_name) for type_name in emitted}


def member_declaration(schema, element, exact_decimals):
    name = element.get("name")
    member = snake(name)
    repeated = element.get("maxOccurs", "1") not in ("1",)
    declared = element.get("type")
    shape, _nested = field_shape(schema, element)

    if shape == "nested":
        return member, "nested", None, repeated
    if shape == "enumeration":
        kind, cpp = "enumeration", "std::int16_t"
    else:
        kind = shape
        cpp = CPP_TYPE[kind]
    # Only a real has digits a double can lose. A text element states them
    # already, and an enumeration is not a number, so the same element name in
    # a different type keeps the kind the schema gives it. A list holding "*"
    # names every real, which is what a family whose numbers all matter states.
    if shape == "real" and ("*" in exact_decimals or name in exact_decimals):
        kind, cpp = "decimal", CPP_TYPE["decimal"]

    if repeated:
        return member, kind, f"std::vector<{cpp}>", True
    return member, kind, cpp, False


# Names the engine already uses in the same namespace. A generated struct that
# took one of them would shadow it and break the engine's own code.
RESERVED = {
    "field",
    "record_type",
    "document_type",
    "event_type",
    "reader",
    "binder",
    "field_kind",
    "scalar_kind",
    "residual_element",
    "bind_error",
    "token",
    "token_kind",
    "document",
    "is_blank",
    "no_text",
}


def cpp_names(schema, ordered):
    """A C++ identifier per schema type, free of the engine's vocabulary.

    The table variables carry a `_record` suffix rather than `_type`, so a
    struct called DatesType and the table of a struct called Dates cannot
    collide.
    """
    names = {}
    taken = set()
    for type_name in ordered:
        candidate = snake(type_name)
        while candidate in taken or candidate in RESERVED:
            candidate = "record_" + candidate
        taken.add(candidate)
        names[type_name] = candidate
    return names


def shadowed_types(schema, ordered, names):
    """The (struct, type) pairs where a member hides the type it names.

    A member may be named after its own type. Clang accepts `data data;`, but
    gcc rejects it with -Wchanges-meaning, because the name means the type in
    the declaration and the member after it. A different member of the record
    with that name, written before or after the use, changes the meaning the
    same way. In every case the type is spelled with the `struct` keyword so
    it still resolves. This is the only place the generator needs that
    spelling, so no type has to be renamed for it.
    """
    # The members are listed in the order the record declares them, which is
    # the order render writes them: attributes first, then elements.
    fields = {}
    for type_name in ordered:
        elements, attributes = children_of(schema.complex_types[type_name], schema)
        held = [(snake(attribute.get("name")), None) for attribute in attributes]
        for element in elements:
            for field in expand(schema, element):
                if not field.get("name"):
                    continue
                target = field.get("type") or schema.inline_name.get(
                    id(field), field.get("name")
                )
                held.append((snake(field.get("name")), target))
        fields[type_name] = held

    shadowed = set()
    for holder, held in fields.items():
        for _member, target in held:
            if target is None or target not in names:
                continue
            name = names[target]
            # Any member of the record takes the type's name: the member
            # itself, one declared before the use, or one declared after it.
            if any(member == name for member, _ in held):
                shadowed.add((holder, target))
    return shadowed


def render(schema, root_element, root_type, namespace, accessor, exact_decimals, include):
    ordered = order_types(schema, root_type)
    names = cpp_names(schema, ordered)
    cut = {(holder, member) for holder, member, _target in schema.cut_members}
    emitted = [name for name in ordered if name in schema.used_types]
    shadowed = shadowed_types(schema, ordered, names)
    counts = member_counts(schema, emitted, names, cut, exact_decimals)
    wide = {t for t, c in counts.items() if c >= WIDE_RECORD_MEMBERS}

    def container(type_name, element):
        return f"std::deque<{element}>" if type_name in wide else f"std::vector<{element}>"

    def ops_arguments(type_name, element):
        """The template arguments of the three functions that grow and index a member."""
        return f"{element}, {container(type_name, element)}" if type_name in wide else element

    header_name = accessor.replace("_document", "")

    unresolved = []
    declarations = []
    declares = []
    for type_name in emitted:
        complex_type = schema.complex_types[type_name]
        elements, attributes = children_of(complex_type, schema)
        declares.append(f"struct {names[type_name]};")
        body = [f"struct {names[type_name]} {{"]
        field_count = 0
        own_kind = content_kind(schema, complex_type)
        if own_kind == "real" and "*" in exact_decimals:
            own_kind = "decimal"
        if own_kind is not None:
            own_cpp = CPP_TYPE[own_kind]
            body.append(f"    {own_cpp} value{CPP_ZERO.get(own_cpp, '')};")
            field_count += 1
        for attribute in attributes:
            body.append(f"    std::string {snake(attribute.get('name'))};")
            field_count += 1
        for element in elements:
            for field in expand(schema, element):
                member, kind, cpp, repeated = member_declaration(schema, field, exact_decimals)
                if kind == "nested":
                    target = field.get("type") or schema.inline_name.get(id(field), field.get("name"))
                    if target not in names:
                        unresolved.append((type_name, member, target))
                        continue
                    cpp = names[target]
                    if (type_name, member) in cut:
                        # A recursive member is an index into an arena this
                        # record owns, so no row of the record moves when the
                        # arena grows.
                        body.append(f"    std::vector<std::uint32_t> {member};")
                        body.append(f"    {container(target, 'struct ' + cpp)} {member}_arena;")
                        field_count += 1
                        continue
                    if (type_name, target) in shadowed:
                        cpp = f"struct {cpp}"
                    if repeated:
                        cpp = container(target, cpp)
                body.append(f"    {cpp} {member}{CPP_ZERO.get(cpp, '')};")
                field_count += 1
        if is_residual(complex_type):
            body.append("    std::vector<residual_element> extras;")
            field_count += 1
        body.append("};")
        words = (field_count + MASK_WORD_BITS - 1) // MASK_WORD_BITS
        if words <= 1:
            body.insert(1, "    std::uint64_t present = 0;")
        else:
            body.insert(1, f"    std::uint64_t present[{words}] = {{0}};")
        declarations.append("\n".join(body))

    if unresolved:
        holder, member, target = unresolved[0]
        raise SystemExit(
            f"{holder}.{member} holds {target}, which is not a complexType this generator read"
        )

    # The cut edges whose target is emitted: the only tables a row names before
    # this file defines them.
    indexed_targets = [
        name
        for name in emitted
        if any(target == name for _holder, _member, target in schema.cut_members)
    ]
    indexed_declarations = ""
    if indexed_targets:
        tables_declared_later = "\n".join(
            f"extern const record_type {names[name]}_record;" for name in indexed_targets
        )
        indexed_declarations = (
            "// A row that indexes an arena names a record, and the edge that closes\n"
            "// a type cycle is always a back edge, so the record is defined later in\n"
            "// this file.\n" + tables_declared_later + "\n\n"
        )
    tables = []
    repeated_members = []
    repeated_arena = []
    for type_name in emitted:
        complex_type = schema.complex_types[type_name]
        elements, attributes = children_of(complex_type, schema)
        rows = []
        bit = 0
        own_kind = content_kind(schema, complex_type)
        if own_kind == "real" and "*" in exact_decimals:
            own_kind = "decimal"
        own_enum = content_enumeration(schema, complex_type)
        if own_kind is not None:
            tokens = f"{snake(own_enum)}_spellings" if own_enum else "nullptr"
            rows.append(
                f'    {{"", 0u, field_kind::{own_kind}, '
                f"std::uint32_t(offsetof({names[type_name]}, value)), "
                f"{bit}, false, false, {tokens}, nullptr, {SCALAR[own_kind]}, nullptr}},"
            )
            bit += 1
        for attribute in attributes:
            name = attribute.get("name")
            required = attribute.get("use") == "required"
            rows.append(
                f'    {{"{name}", {hash_name(name)}u, field_kind::text, '
                f"std::uint32_t(offsetof({names[type_name]}, {snake(name)})), {bit}, true, "
                f"{'true' if required else 'false'}, nullptr, nullptr, "
                f"scalar_kind::text, nullptr}},"
            )
            bit += 1
        for element in elements:
          for element in expand(schema, element):
            name = element.get("name")
            member, kind, cpp, repeated = member_declaration(schema, element, exact_decimals)
            required = element.get("minOccurs", "1") != "0" and id(element) not in CHOICE_CHILDREN
            scalar = SCALAR.get(kind, "scalar_kind::text")
            if kind == "nested":
                target_name = element.get("type") or schema.inline_name.get(
                    id(element), element.get("name")
                )
                if target_name not in names:
                    continue
                member = snake(element.get("name"))
                if (type_name, member) in cut:
                    ops_instance = ops_name(names[type_name], f"{member}_arena")
                    repeated_arena.append((ops_instance, ops_arguments(target_name, names[target_name])))
                    rows.append(
                        f'    {{"{element.get("name")}", {hash_name(element.get("name"))}u, '
                        f"field_kind::indexed_nested, "
                        f"std::uint32_t(offsetof({names[type_name]}, {member})), "
                        f"{bit}, false, {'true' if required else 'false'}, nullptr, "
                        f"&{names[target_name]}_record, "
                        f"scalar_kind::text, &{ops_instance}, "
                        f"std::uint32_t(offsetof({names[type_name]}, {member}_arena)), "
                        f"{'true' if not repeated else 'false'}}},"
                    )
                    bit += 1
                    continue
                field_kind = "repeated_nested" if repeated else "nested"
                nested = names[
                    element.get("type") or schema.inline_name.get(id(element), element.get("name"))
                ]
                ops = "nullptr"
                if repeated:
                    ops = f"&{ops_name(names[type_name], member)}"
                    repeated_members.append(
                        (ops_name(names[type_name], member), ops_arguments(target_name, nested))
                    )
                rows.append(
                    f'    {{"{name}", {hash_name(name)}u, field_kind::{field_kind}, '
                    f"std::uint32_t(offsetof({names[type_name]}, {member})), {bit}, false, "
                    f"{'true' if required else 'false'}, nullptr, "
                    f"&{nested}_record, scalar_kind::text, {ops}}},"
                )
            else:
                # A repeated leaf is one value of the element's own kind, so
                # the row says which kind that is and the engine stores that.
                field_kind = "repeated_leaf" if repeated else kind
                tokens = (
                    spellings_of(schema, type_name, element) or "nullptr"
                    if kind == "enumeration"
                    else "nullptr"
                )
                ops = "nullptr"
                if repeated:
                    ops = f"&{ops_name(names[type_name], member)}"
                    repeated_members.append(
                        (ops_name(names[type_name], member), vector_element_type(cpp))
                    )
                rows.append(
                    f'    {{"{name}", {hash_name(name)}u, field_kind::{field_kind}, '
                    f"std::uint32_t(offsetof({names[type_name]}, {member})), {bit}, false, "
                    f"{'true' if required else 'false'}, {tokens}, nullptr, {scalar}, {ops}}},"
                )
            bit += 1
        if is_residual(complex_type):
            rows.append(
                f'    {{"", 0u, field_kind::residual, '
                f"std::uint32_t(offsetof({names[type_name]}, extras)), "
                f"{bit}, false, false, nullptr, nullptr, scalar_kind::text, nullptr}},"
            )
            bit += 1
        if bit > MAX_MASK_BITS:
            raise SystemExit(
                f"{type_name} has {bit} fields; a table holds {MAX_MASK_BITS} at most"
            )
        text_field = "0" if own_kind is not None else "no_text"
        tables.append(
            f"const field {names[type_name]}_fields[] = {{\n"
            + "\n".join(rows)
            + f"\n}};\nconst record_type {names[type_name]}_record{{\"{type_name}\", "
            f"{names[type_name]}_fields, {bit}, {text_field}}};"
        )

    ops = []
    for instance, arguments in repeated_arena + repeated_members:
        ops.append(
            f"constexpr vector_ops {instance}{{&append_to<{arguments}>, "
            f"&count_of<{arguments}>, &at_of<{arguments}>}};"
        )

    spellings = []
    emitted_spellings = set()
    for type_name in ordered:
        base = content_enumeration(schema, schema.complex_types[type_name])
        if base is not None and base not in emitted_spellings:
            emitted_spellings.add(base)
            values = ", ".join(f'"{v}"' for v in schema.enumerations[base])
            spellings.append(
                f"const char* {snake(base)}_spellings[] = {{{values}, nullptr}};"
            )
    for type_name in ordered:
        for element in children_of(schema.complex_types[type_name], schema)[0]:
            for field in expand(schema, element):
                # The spellings of an inline enumeration are registered when its
                # shape is read, and a member reached here may not have been.
                field_shape(schema, field)
                declared = field.get("type")
                if id(field) in schema.inline_enum:
                    name = spellings_of(schema, type_name, field)
                    if name not in emitted_spellings:
                        emitted_spellings.add(name)
                        values = ", ".join(f'"{v}"' for v in schema.inline_enum[id(field)])
                        spellings.append(
                            f"const char* {name}[] = {{{values}, nullptr}};"
                        )
                elif declared in schema.enumerations and declared not in emitted_spellings:
                    emitted_spellings.add(declared)
                    values = ", ".join(f'"{v}"' for v in schema.enumerations[declared])
                    spellings.append(
                        f"const char* {snake(declared)}_spellings[] = "
                        f"{{{values}, nullptr}};"
                    )

    header = f'''{LICENCE}#ifndef ORES_ORE_CORE_XML_GENERATED_{header_name.upper()}_HPP
#define ORES_ORE_CORE_XML_GENERATED_{header_name.upper()}_HPP

#include "ores.ore.core/xml/binding.hpp"
#include "ores.utility/decimal/decimal.hpp"

#include <cstdint>
{'#include <deque>' + chr(10) if wide else ''}#include <string>
#include <vector>

namespace {namespace} {{

{chr(10).join(declares)}

{chr(10).join(declarations)}

ORES_ORE_CORE_EXPORT auto {accessor}() -> const document_type&;

}}

#endif
'''

    source = f'''{LICENCE}#include "{include}"

#include <cstddef>

namespace {namespace} {{

namespace {{

constexpr std::uint8_t no_text = 0xFF;

template <typename T, typename Container = std::vector<T>>
auto append_to(void* container, void** slot) -> void {{
    auto* held = static_cast<Container*>(container);
    held->emplace_back();
    *slot = &held->back();
}}

template <typename T, typename Container = std::vector<T>>
auto count_of(const void* container) -> std::size_t {{
    return static_cast<const Container*>(container)->size();
}}

template <typename T, typename Container = std::vector<T>>
auto at_of(const void* container, std::size_t index) -> const void* {{
    return &(*static_cast<const Container*>(container))[index];
}}

{chr(10).join(spellings)}

{chr(10).join(ops)}

{indexed_declarations}{chr(10).join(tables)}

}}

ORES_ORE_CORE_EXPORT auto {accessor}() -> const document_type& {{
    static const document_type doc{{"{root_element}", &{names[root_type]}_record}};
    return doc;
}}

}}
'''
    return header, source


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", action="append", required=True)
    parser.add_argument("--root-element", required=True)
    parser.add_argument("--root-type", required=True)
    parser.add_argument("--namespace", default="ores::ore::xml::generated")
    parser.add_argument("--accessor", required=True)
    parser.add_argument("--include", default="")
    parser.add_argument("--header", required=True)
    parser.add_argument("--source", required=True)
    parser.add_argument(
        "--exact-decimal",
        action="append",
        default=[],
        dest="exact_decimals",
        help="real element carried as an exact decimal; '*' names every real",
    )
    args = parser.parse_args()

    schema = Schema(args.schema)
    if args.root_type not in schema.complex_types:
        raise SystemExit(f"no complexType {args.root_type}")
    default_include = (
        "ores.ore.core/xml/generated/" + args.accessor.replace("_document", "") + ".hpp"
    )
    header, source = render(
        schema,
        args.root_element,
        args.root_type,
        args.namespace,
        args.accessor,
        set(args.exact_decimals),
        args.include or default_include,
    )
    with open(args.header, "w", encoding="utf-8") as handle:
        handle.write(header)
    with open(args.source, "w", encoding="utf-8") as handle:
        handle.write(source)
    sys.stderr.write(f"wrote {args.header} and {args.source}\n")


if __name__ == "__main__":
    main()

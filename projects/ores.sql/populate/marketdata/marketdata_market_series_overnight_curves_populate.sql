/**
 * Overnight-Index Curve Market Series Population Script
 *
 * Seeds, for each currency that
 * refdata_ir_curve_overnight_configs_populate.sql gives a curve, the two
 * market_series rows its overnight-index curve needs, as
 * marketdata_market_series_ir_curve_populate.sql does for USD:
 *
 *  - the bootstrapped curve the republish service writes into, named by the
 *    curve's config, such as
 *    oresmd://ir/EUR?type=series&instrument=discount&quote=rate&curve_id=EUR-ESTR,
 *    seeded OBSERVED with the sentinel and stamped IR_CURVE_BOOTSTRAP on its
 *    first republish;
 *
 *  - the ladder its quotes come from: the spot-starting overnight-index swap
 *    quote the synthetic Bloomberg feed publishes for the currency, one datum per
 *    term from 1M to 30Y. The ingest loop finds this row by its identity,
 *    provider and party and writes the feed's ticks into it.
 *
 * The system party's subscription and route to bloomberg-a, seeded by the USD
 * script, cover these ladders too.
 *
 * This script is idempotent - uses INSERT ON CONFLICT DO NOTHING.
 */


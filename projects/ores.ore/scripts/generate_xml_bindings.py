#!/usr/bin/env python3
"""Emit the C++ records and codec tables for one ORE document family.

The generator reads the authoritative schema, so the table cannot disagree
with ORE about which elements exist, their order, their cardinality or their
type. Two things the schema does not say and this file does:

- the C++ name of each member, which is the element name in snake case;
- what a numeric element *means* to us. ORE types the same money concept as
  xs:float, xs:double and xs:string in three places, so the kind arrives from
  a money vocabulary supplied on the command line rather than from the schema.

Output is two files: a header with the records and the accessor, and a source
with the tables. Both carry the generated marker so tooling skips them.
"""

import argparse
import re
import sys
import xml.etree.ElementTree as ET

PRIMITIVES = {
    "xs:string": "text",
    "xs:integer": "integer",
    "xs:int": "integer",
    "xs:long": "integer",
    "xs:decimal": "decimal",
    "xs:double": "real",
    "xs:float": "real",
    "xs:date": "text",
    "xs:time": "text",
    "xs:dateTime": "text",
    "xs:boolean": "text",
    "xs:nonNegativeInteger": "integer",
    "xs:positiveInteger": "integer",
    "xs:unsignedInt": "integer",
    "xs:unsignedLong": "integer",
    "xs:unsignedShort": "integer",
    "xs:byte": "integer",
    "xs:short": "integer",
    "xs:anyURI": "text",
    "xs:token": "text",
    "xs:normalizedString": "text",
}

CPP_TYPE = {
    "text": "std::string",
    "integer": "std::int64_t",
    "decimal": "ores::utility::decimal::decimal",
    "real": "double",
}

SCALAR = {
    "text": "scalar_kind::text",
    "integer": "scalar_kind::integer",
    "decimal": "scalar_kind::decimal",
    "real": "scalar_kind::real",
}

